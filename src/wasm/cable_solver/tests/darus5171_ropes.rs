//! Multi-rope storage-tension and running-radius validation against DaRUS-5171 (2026 thesis).
//!
//! Tests three distinct 6 mm 12-strand braided ropes (LIROS D-Pro XTR Dyneema, Trowis Vectran
//! HT T190, Trowis PolyTrop FOX Polyester/TPU) across two splits:
//!   1. `darus5171_fdp_fc_map.csv` — identification split (5 storage tensions F_S x 5 unwinding
//!      tensions F_L = 25 runs per rope) separating axial stiffness EA from drum running-radius
//!      flattening k_r.
//!   2. `darus5171_stat_valid.csv` — held-out `StatCompensationValid` split (3x3 F_S x F_L at
//!      +2 and +3 m/s) evaluated blindly with frozen (EA, k_r) from split 1.
//!
//! Fixtures generated by `scripts/reference_data/summarize_5171.py`.
mod common;
use common::*;

const SPOOL_END: f64 = 3.0;
/// Nominal SWP/CATi drum radius (100.36 mm nominal diameter).
const RADIUS: f64 = 0.05018;
const SPEED: f64 = 2.0;

/// Simulate the DaRUS-5171 FDP-FC-MAP two-phase protocol in `PhysicsWorld`:
///   1. Wind 10 m onto the test drum at storage tension `f_s`.
///   2. Re-tension the span to `f_l` (preload controller).
///   3. Unwind 10 m off the test drum onto the load drum while servoing the load drum to hold `f_l`.
///
/// Returns `(lsv_ratio, drum_l_ratio)` during the unwinding pass.
fn wind_then_unwind(f_s: f64, f_l: f64, ea: f64, k_r: f64) -> (f64, f64) {
    let span = 2.0;
    let test = wheel(0, [-span / 2.0, 0.0, 0.0], RADIUS, 0.5, 1e6, None);
    let load = wheel(1, [span / 2.0, 0.0, 0.0], RADIUS, 0.5, 1e6, None);
    let segs = [Seg {
        a: 0,
        b: 1,
        rest: span / (1.0 + f_s / ea),
        pa: [-span / 2.0, RADIUS, 0.0],
        pb: [span / 2.0, RADIUS, 0.0],
    }];
    // Link 0 = test drum (cw=false: +omega winds onto drum, -omega unwinds).
    // Link 1 = load drum (cw=true: -omega winds onto drum, +omega unwinds).
    let links = [(SPOOL_END, false, 5.0), (SPOOL_END, true, 15.0)];
    let mut w = world(vec![test, load], vec![path(&links, &segs, ea, 0.0, 4.0)]);
    w.options[1] = 0.0;
    w.options[19] = k_r;
    w.options[20] = 1.0; // strained spool storage with LIFO storage-tension memory

    let dt = 0.002;
    let mat0 = material(&mut w, 0);

    // Phase 1: Wind 10.5 m onto test drum at constant tension f_s.
    let wind_steps = (10.5 / SPEED / dt) as usize;
    for _ in 0..wind_steps {
        for id in 0..2 {
            w.entities[id][72..75].copy_from_slice(&[0.0, 0.0, SPEED / RADIUS]);
        }
        w.step(dt).unwrap();
    }

    // Phase 2: Hold test drum fixed and adjust load drum so span tension equals f_l.
    let target_rest = span / (1.0 + f_l / ea);
    let cur_rest = rest(&mut w, 0, 0);
    let delta_rest = cur_rest - target_rest; // >0 means load drum must wind in to raise tension
    let jo = HEADER + 2 * LINK;
    w.path_data(0)[jo + 3] = target_rest;
    // Preserve total material by moving delta_rest into load drum storage.
    let lo1 = HEADER + LINK;
    w.path_data(0)[lo1 + 2] += delta_rest;
    // Step briefly at zero speed so segment_tension caches f_l before unwinding begins.
    for _ in 0..5 {
        for id in 0..2 {
            w.entities[id][72..75].copy_from_slice(&[0.0, 0.0, 0.0]);
        }
        w.step(dt).unwrap();
    }

    // Phase 3: Unwind 10 m off test drum at SPEED, servoing load drum speed to hold tension f_l.
    // The exact steady-state load-drum speed matches rest-length intake to test-drum output:
    //   rho(f) = ((R - k_r*f)/R) / (1 + f/EA)
    // Plus gentle proportional feedback on tension error to mimic the rig's preload controller.
    let rho = |f: f64| ((RADIUS - k_r * f) / RADIUS).max(0.5) / (1.0 + f / ea);
    let ff_ratio = rho(f_s) / rho(f_l);

    let (angle_t0, angle_l0) = (w.entities[0][66], w.entities[1][66]);
    let (mut rope, mut tensions) = (0.0, 0.0);
    let unwind_steps = (10.0 / SPEED / dt) as usize;
    for _ in 0..unwind_steps {
        let before = stored(&mut w, 0, 0);
        let t_now = tension(&mut w, 0, 0);
        // Proportional preload servo on load drum speed (faster -omega winds more, raising tension).
        let v_load = SPEED * ff_ratio + 2e-4 * (f_l - t_now);
        w.entities[0][72..75].copy_from_slice(&[0.0, 0.0, -SPEED / RADIUS]);
        w.entities[1][72..75].copy_from_slice(&[0.0, 0.0, -v_load / RADIUS]);
        w.step(dt).unwrap();
        let t = tension(&mut w, 0, 0);
        rope += (before - stored(&mut w, 0, 0)) * (1.0 + t / ea);
        tensions += t;
    }

    let drum_t = (w.entities[0][66] - angle_t0).abs() * RADIUS;
    let drum_l = (w.entities[1][66] - angle_l0).abs() * RADIUS;
    let mean_t = tensions / unwind_steps as f64;
    let mat1 = material(&mut w, 0);
    assert!((mat1 - mat0).abs() < 1e-8, "material conservation violated: {mat0} -> {mat1}");
    assert!((mean_t - f_l).abs() < 0.02 * f_l, "mean tension {mean_t:.2} vs {f_l:.2}");
    (rope / drum_t, drum_l / drum_t)
}

/// Ordinary least squares for `y = b0 + b1*x1 + b2*x2`.
fn fit_plane(x1: &[f64], x2: &[f64], y: &[f64]) -> ([f64; 3], f64) {
    let n = y.len() as f64;
    let mut a = [[0.0; 3]; 3];
    let mut b = [0.0; 3];
    for ((&u, &v), &w) in x1.iter().zip(x2).zip(y) {
        let r = [1.0, u, v];
        for i in 0..3 {
            b[i] += r[i] * w;
            for j in 0..3 {
                a[i][j] += r[i] * r[j];
            }
        }
    }
    // 3x3 Gaussian elimination with partial pivoting.
    let mut m = [[0.0; 4]; 3];
    for i in 0..3 {
        m[i][..3].copy_from_slice(&a[i]);
        m[i][3] = b[i];
    }
    for col in 0..3 {
        let pivot = (col..3).max_by(|&i, &j| m[i][col].abs().total_cmp(&m[j][col].abs())).unwrap();
        m.swap(col, pivot);
        let div = m[col][col];
        for k in col..4 {
            m[col][k] /= div;
        }
        for row in 0..3 {
            if row != col {
                let f = m[row][col];
                for k in col..4 {
                    m[row][k] -= f * m[col][k];
                }
            }
        }
    }
    let coef = [m[0][3], m[1][3], m[2][3]];
    let sse: f64 = x1
        .iter()
        .zip(x2)
        .zip(y)
        .map(|((&u, &v), &w)| (w - (coef[0] + coef[1] * u + coef[2] * v)).powi(2))
        .sum();
    (coef, (sse / n).sqrt())
}

struct IdentRow {
    rope: String,
    f_s: f64,
    f_l: f64,
    lsv_ratio: f64,
    drum_l_ratio: f64,
}

struct ValidRow {
    rope: String,
    f_s: f64,
    f_l: f64,
    speed: f64,
    lsv_ratio: f64,
}

fn load_ident() -> Vec<IdentRow> {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../../tests/fixtures/reference_data/darus5171_fdp_fc_map.csv");
    let text = std::fs::read_to_string(path).unwrap();
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next().unwrap().split(',').collect();
    let col = |name: &str| header.iter().position(|&h| h == name).unwrap();
    lines
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            let f: Vec<&str> = l.split(',').collect();
            IdentRow {
                rope: f[col("rope")].to_string(),
                f_s: f[col("f_wind")].parse().unwrap(),
                f_l: f[col("f_unwind")].parse().unwrap(),
                lsv_ratio: f[col("lsv_ratio")].parse().unwrap(),
                drum_l_ratio: f[col("drum_l_ratio")].parse().unwrap(),
            }
        })
        .collect()
}

fn load_valid() -> Vec<ValidRow> {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../../tests/fixtures/reference_data/darus5171_stat_valid.csv");
    let text = std::fs::read_to_string(path).unwrap();
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next().unwrap().split(',').collect();
    let col = |name: &str| header.iter().position(|&h| h == name).unwrap();
    lines
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            let f: Vec<&str> = l.split(',').collect();
            ValidRow {
                rope: f[col("rope")].to_string(),
                f_s: f[col("f_s_nom")].parse().unwrap(),
                f_l: f[col("f_unwind")].parse().unwrap(),
                speed: f[col("speed_test")].parse().unwrap(),
                lsv_ratio: f[col("lsv_ratio")].parse().unwrap(),
            }
        })
        .collect()
}

/// Identify `(EA, k_r)` per rope from DaRUS-5171 `FDP-FC-MAP` and verify `PhysicsWorld`
/// reproduces both storage-tension (`c_FS`) and unwinding-tension (`c_FL`) slopes on the
/// optical LSV ratio AND the encoder-only `drumL/drumT` ratio across all three rope materials.
#[test]
fn multi_rope_storage_and_unwinding_slopes_match_solver() {
    let rows = load_ident();
    for rope in ["LIROS_D-Pro", "Trowis_VectranHT_T190PU", "Trowis_PolyTropFOX"] {
        let sub: Vec<&IdentRow> = rows.iter().filter(|r| r.rope == rope).collect();
        assert_eq!(sub.len(), 25, "expected 25 FDP-FC-MAP runs for {rope}");
        let fs: Vec<f64> = sub.iter().map(|r| r.f_s).collect();
        let fl: Vec<f64> = sub.iter().map(|r| r.f_l).collect();
        let lsv_ppm: Vec<f64> = sub.iter().map(|r| (r.lsv_ratio - 1.0) * 1e6).collect();
        let dl_ppm: Vec<f64> = sub.iter().map(|r| (r.drum_l_ratio - 1.0) * 1e6).collect();

        let (meas_lsv, meas_rms) = fit_plane(&fs, &fl, &lsv_ppm);
        let (meas_dl, _) = fit_plane(&fs, &fl, &dl_ppm);
        let ea = 1e6 / meas_lsv[2];
        let alpha_r = -(meas_lsv[1] + meas_lsv[2]) * 1e-6;
        let k_r = alpha_r * RADIUS;

        // Simulate a 3x3 (F_S, F_L) grid in PhysicsWorld using the identified (EA, k_r).
        let grid = [75.0, 130.0, 180.0];
        let (mut sim_fs, mut sim_fl, mut sim_lsv, mut sim_dl) = (vec![], vec![], vec![], vec![]);
        for &s in &grid {
            for &l in &grid {
                let (r_lsv, r_dl) = wind_then_unwind(s, l, ea, k_r);
                sim_fs.push(s);
                sim_fl.push(l);
                sim_lsv.push((r_lsv - 1.0) * 1e6);
                sim_dl.push((r_dl - 1.0) * 1e6);
            }
        }
        let (sim_c, _) = fit_plane(&sim_fs, &sim_fl, &sim_lsv);
        let (sim_dlc, _) = fit_plane(&sim_fs, &sim_fl, &sim_dl);
        eprintln!(
            "{rope:24}: EA={:5.1} kN, k_r={:5.3} um/N | LSV (c_FS, c_FL) meas=({:+.2}, {:+.2}) sim=({:+.2}, {:+.2}) rms={meas_rms:.0} ppm | drumL meas=({:+.2}, {:+.2}) sim=({:+.2}, {:+.2})",
            ea * 1e-3,
            k_r * 1e6,
            meas_lsv[1],
            meas_lsv[2],
            sim_c[1],
            sim_c[2],
            meas_dl[1],
            meas_dl[2],
            sim_dlc[1],
            sim_dlc[2],
        );
        assert!((sim_c[1] - meas_lsv[1]).abs() < 1.0, "{rope} c_FS mismatch");
        assert!((sim_c[2] - meas_lsv[2]).abs() < 1.0, "{rope} c_FL mismatch");
        // Encoder-to-encoder drumL/drumT slopes are equal and opposite in the solver.
        assert!((sim_dlc[1] + sim_dlc[2]).abs() < 0.5, "{rope} drumL not antisymmetric");
        assert!((sim_dlc[1] - meas_dl[1]).abs() < 3.0, "{rope} drumL c_FS mismatch");
    }
}

/// Blind held-out validation: freeze `(EA, k_r)` identified on `FDP-FC-MAP`, then predict
/// the held-out `StatCompensationValid` runs (3x3 F_S x F_L at +2 and +3 m/s) in `PhysicsWorld`
/// without refitting (removing only the constant sensor-scale intercept per rope).
#[test]
fn blind_validation_on_held_out_stat_compensation_runs() {
    let ident = load_ident();
    let valid = load_valid();

    // Bare 12-strand braids (Dyneema, Vectran) land inside the LSV's ~100-200 ppm repeat noise floor;
    // TPU-jacketed PolyTropFOX has ~1000 ppm viscoelastic/jacket scatter even in its ident split (thesis Table 4.10).
    for (rope, max_rmse_ppm, min_reduction) in [
        ("LIROS_D-Pro", 200.0, 75.0),
        ("Trowis_VectranHT_T190PU", 200.0, 75.0),
        ("Trowis_PolyTropFOX", 1100.0, 25.0),
    ] {
        // Fit (EA, k_r) strictly on identification split.
        let id_sub: Vec<&IdentRow> = ident.iter().filter(|r| r.rope == rope).collect();
        let fs: Vec<f64> = id_sub.iter().map(|r| r.f_s).collect();
        let fl: Vec<f64> = id_sub.iter().map(|r| r.f_l).collect();
        let lsv_ppm: Vec<f64> = id_sub.iter().map(|r| (r.lsv_ratio - 1.0) * 1e6).collect();
        let (coef, _) = fit_plane(&fs, &fl, &lsv_ppm);
        let ea = 1e6 / coef[2];
        let k_r = -(coef[1] + coef[2]) * 1e-6 * RADIUS;

        // Evaluate blindly on held-out StatCompensationValid runs.
        let val_sub: Vec<&ValidRow> = valid.iter().filter(|r| r.rope == rope).collect();
        assert!(!val_sub.is_empty(), "no held-out validation runs for {rope}");

        let mut errs = Vec::with_capacity(val_sub.len());
        let mut meas_vals = Vec::with_capacity(val_sub.len());
        for r in &val_sub {
            let (pred_ratio, _) = wind_then_unwind(r.f_s, r.f_l, ea, k_r);
            let meas_ppm = (r.lsv_ratio - 1.0) * 1e6;
            let pred_ppm = (pred_ratio - 1.0) * 1e6;
            errs.push(meas_ppm - pred_ppm);
            meas_vals.push(meas_ppm);
        }
        // Remove constant absolute-scale intercept (LSV absolute accuracy is +/-500 ppm).
        let mean_err = errs.iter().sum::<f64>() / errs.len() as f64;
        let rmse_pred = (errs.iter().map(|e| (e - mean_err).powi(2)).sum::<f64>() / errs.len() as f64).sqrt();
        let mean_meas = meas_vals.iter().sum::<f64>() / meas_vals.len() as f64;
        let rmse_base = (meas_vals.iter().map(|m| (m - mean_meas).powi(2)).sum::<f64>() / meas_vals.len() as f64).sqrt();
        let reduction = 100.0 * (1.0 - rmse_pred / rmse_base);
        eprintln!(
            "[BLIND VALID] {rope:24} (n={:2}, speeds {:?}..{:?} m/s): baseline={rmse_base:6.1} ppm -> solver={rmse_pred:5.1} ppm ({reduction:+.1}% reduction)",
            val_sub.len(),
            val_sub.iter().map(|r| r.speed).fold(f64::INFINITY, f64::min).round(),
            val_sub.iter().map(|r| r.speed).fold(f64::NEG_INFINITY, f64::max).round(),
        );
        assert!(
            rmse_pred < max_rmse_ppm,
            "{rope} blind validation RMSE {rmse_pred:.1} ppm exceeded {max_rmse_ppm:.1} ppm"
        );
        assert!(reduction > min_reduction, "{rope} error reduction {reduction:.1}% below {min_reduction:.1}%");
    }
}
